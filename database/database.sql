-- Buat tabel tanpa menghapus data yang sudah ada saat skrip dijalankan ulang.


-- =========================================================
-- 1. SUPPLIER
-- =========================================================

CREATE TABLE IF NOT EXISTS supplier (
    id_supplier BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_supplier VARCHAR(100) NOT NULL,
    alamat TEXT,
    no_telp VARCHAR(20)
);


-- =========================================================
-- 2. UTANG
-- =========================================================

CREATE TABLE IF NOT EXISTS utang (
    id_utang BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_supplier BIGINT NOT NULL,

    tanggal_utang DATE NOT NULL,

    jatuh_tempo DATE,

    jumlah_utang NUMERIC(15,2) NOT NULL
        CHECK (jumlah_utang > 0),

    status VARCHAR(20) NOT NULL DEFAULT 'Belum Lunas'
        CHECK (
            status IN (
                'Belum Lunas',
                'Sebagian',
                'Lunas'
            )
        ),

    CONSTRAINT fk_utang_supplier
        FOREIGN KEY (id_supplier)
        REFERENCES supplier(id_supplier)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- =========================================================
-- 3. PEMBAYARAN
-- =========================================================

CREATE TABLE IF NOT EXISTS pembayaran (
    id_pembayaran BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    tanggal_pembayaran DATE NOT NULL,

    metode_pembayaran VARCHAR(30) NOT NULL DEFAULT 'Tunai'
);


-- =========================================================
-- 4. DETAIL PEMBAYARAN
-- =========================================================

CREATE TABLE IF NOT EXISTS detail_pembayaran (
    id_detail BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_pembayaran BIGINT NOT NULL,

    id_utang BIGINT NOT NULL,

    jumlah_bayar NUMERIC(15,2) NOT NULL
        CHECK (jumlah_bayar > 0),

    CONSTRAINT fk_detail_pembayaran
        FOREIGN KEY (id_pembayaran)
        REFERENCES pembayaran(id_pembayaran)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_detail_utang
        FOREIGN KEY (id_utang)
        REFERENCES utang(id_utang)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- =========================================================
-- INDEX
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_utang_supplier
ON utang(id_supplier);

CREATE INDEX IF NOT EXISTS idx_detail_pembayaran
ON detail_pembayaran(id_pembayaran);

CREATE INDEX IF NOT EXISTS idx_detail_utang
ON detail_pembayaran(id_utang);


