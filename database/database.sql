CREATE OR REPLACE FUNCTION public.perbarui_utang(
    p_id_utang BIGINT,
    p_id_supplier BIGINT,
    p_tanggal_utang DATE,
    p_jatuh_tempo DATE,
    p_jumlah_utang NUMERIC
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
    v_sudah_dibayar NUMERIC(15,2);
    v_status VARCHAR(20);
BEGIN
    IF p_jumlah_utang IS NULL OR p_jumlah_utang <= 0 OR p_tanggal_utang IS NULL THEN
        RAISE EXCEPTION 'Tanggal dan jumlah utang yang valid wajib diisi.';
    END IF;

    PERFORM 1
    FROM public.utang
    WHERE id_utang = p_id_utang
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Utang tidak ditemukan atau tidak dapat diakses.';
    END IF;

    SELECT COALESCE(SUM(jumlah_bayar), 0)
    INTO v_sudah_dibayar
    FROM public.detail_pembayaran
    WHERE id_utang = p_id_utang;

    IF p_jumlah_utang < v_sudah_dibayar THEN
        RAISE EXCEPTION 'Jumlah utang tidak boleh lebih kecil dari pembayaran yang sudah tercatat (%).',
            v_sudah_dibayar;
    END IF;

    v_status := CASE
        WHEN v_sudah_dibayar >= p_jumlah_utang THEN 'Lunas'
        WHEN v_sudah_dibayar > 0 THEN 'Sebagian'
        ELSE 'Belum Lunas'
    END;

    UPDATE public.utang
    SET id_supplier = p_id_supplier,
        tanggal_utang = p_tanggal_utang,
        jatuh_tempo = p_jatuh_tempo,
        jumlah_utang = p_jumlah_utang,
        status = v_status
    WHERE id_utang = p_id_utang;
END;
$$;

CREATE OR REPLACE FUNCTION public.catat_pembayaran(
    p_id_utang BIGINT,
    p_tanggal DATE,
    p_metode VARCHAR,
    p_jumlah NUMERIC
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
    v_jumlah_utang NUMERIC(15,2);
    v_sudah_dibayar NUMERIC(15,2);
    v_id_pembayaran BIGINT;
    v_total_dibayar NUMERIC(15,2);
    v_status VARCHAR(20);
BEGIN
    IF p_tanggal IS NULL OR p_jumlah IS NULL OR p_jumlah <= 0 THEN
        RAISE EXCEPTION 'Tanggal dan jumlah pembayaran yang valid wajib diisi.';
    END IF;

    SELECT jumlah_utang
    INTO v_jumlah_utang
    FROM public.utang
    WHERE id_utang = p_id_utang
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Utang tidak ditemukan atau tidak dapat diakses.';
    END IF;

    SELECT COALESCE(SUM(jumlah_bayar), 0)
    INTO v_sudah_dibayar
    FROM public.detail_pembayaran
    WHERE id_utang = p_id_utang;

    IF p_jumlah > v_jumlah_utang - v_sudah_dibayar THEN
        RAISE EXCEPTION 'Pembayaran melebihi sisa utang sebesar %.',
            v_jumlah_utang - v_sudah_dibayar;
    END IF;

    INSERT INTO public.pembayaran (tanggal_pembayaran, metode_pembayaran)
    VALUES (p_tanggal, COALESCE(NULLIF(BTRIM(p_metode), ''), 'Tunai'))
    RETURNING id_pembayaran INTO v_id_pembayaran;

    INSERT INTO public.detail_pembayaran (id_pembayaran, id_utang, jumlah_bayar)
    VALUES (v_id_pembayaran, p_id_utang, p_jumlah);

    v_total_dibayar := v_sudah_dibayar + p_jumlah;
    v_status := CASE
        WHEN v_total_dibayar >= v_jumlah_utang THEN 'Lunas'
        WHEN v_total_dibayar > 0 THEN 'Sebagian'
        ELSE 'Belum Lunas'
    END;

    UPDATE public.utang
    SET status = v_status
    WHERE id_utang = p_id_utang;

    RETURN v_id_pembayaran;
END;
$$;

CREATE OR REPLACE FUNCTION public.hapus_pembayaran(p_id_detail BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
    v_id_utang BIGINT;
    v_id_pembayaran BIGINT;
    v_jumlah_utang NUMERIC(15,2);
    v_total_dibayar NUMERIC(15,2);
    v_status VARCHAR(20);
BEGIN
    SELECT id_utang, id_pembayaran
    INTO v_id_utang, v_id_pembayaran
    FROM public.detail_pembayaran
    WHERE id_detail = p_id_detail;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Pembayaran tidak ditemukan atau tidak dapat diakses.';
    END IF;

    SELECT jumlah_utang
    INTO v_jumlah_utang
    FROM public.utang
    WHERE id_utang = v_id_utang
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Utang tidak ditemukan atau tidak dapat diakses.';
    END IF;

    DELETE FROM public.detail_pembayaran
    WHERE id_detail = p_id_detail;

    IF NOT EXISTS (
        SELECT 1
        FROM public.detail_pembayaran
        WHERE id_pembayaran = v_id_pembayaran
    ) THEN
        DELETE FROM public.pembayaran
        WHERE id_pembayaran = v_id_pembayaran;
    END IF;

    SELECT COALESCE(SUM(jumlah_bayar), 0)
    INTO v_total_dibayar
    FROM public.detail_pembayaran
    WHERE id_utang = v_id_utang;

    v_status := CASE
        WHEN v_total_dibayar >= v_jumlah_utang THEN 'Lunas'
        WHEN v_total_dibayar > 0 THEN 'Sebagian'
        ELSE 'Belum Lunas'
    END;

    UPDATE public.utang
    SET status = v_status
    WHERE id_utang = v_id_utang;
END;
$$;

